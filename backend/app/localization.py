def translate_doc_name(doc: str, lang: str) -> str:
    """Translate common document names into the target Indian language."""
    if not doc or lang == "en":
        return doc
    dl = doc.lower()
    for key, trans_dict in DOC_TRANSLATIONS.items():
        if key in dl and lang in trans_dict:
            return trans_dict[lang]
    return doc


