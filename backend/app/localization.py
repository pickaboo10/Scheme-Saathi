def translate_mode(mode: str, lang: str) -> str:
    """Translate a single application mode name."""
    if not mode or lang == "en":
        return mode
    ml = mode.lower()
    if "online" in ml and "offline" in ml:
        return "ऑनलाइन / ऑफलाइन" if lang == "hi" else mode
    if "online" in ml:
        return "ऑनलाइन" if lang == "hi" else mode
    if "offline" in ml:
        return "ऑफलाइन" if lang == "hi" else mode
    return mode


